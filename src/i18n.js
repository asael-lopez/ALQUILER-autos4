export function translateText(value, language) {
    if (language !== 'en' || typeof value !== 'string') return value;
    const text = value.trim();
    const translated = englishTranslations[text];
    if (translated !== undefined) {
        return value.replace(text, translated);
    }

    const optionsMatch = text.match(/^(\d+) opciones de categoría de vehículo disponibles$/i);
    if (optionsMatch) {
        const count = Number(optionsMatch[1]);
        const result = `${count} vehicle ${count === 1 ? 'category option' : 'category options'} available`;
        return value.replace(text, result);
    }

    const reservationsMatch = text.match(/^(\d+) reservas$/i);
    if (reservationsMatch) {
        const count = Number(reservationsMatch[1]);
        return value.replace(text, `${count} ${count === 1 ? 'reservation' : 'reservations'}`);
    }

    const maintenanceMatch = text.match(/^Mantenimiento \((\d+)\)$/i);
    if (maintenanceMatch) {
        return value.replace(text, `Maintenance (${maintenanceMatch[1]})`);
    }

    const passengerMatch = text.match(/^(\d+) pasajeros$/i);
    if (passengerMatch) {
        return value.replace(text, `${passengerMatch[1]} passengers`);
    }

    const luggageMatch = text.match(/^(\d+) maletas$/i);
    if (luggageMatch) {
        return value.replace(text, `${luggageMatch[1]} bags`);
    }

    const fleetOccupancyMatch = text.match(/^(\d+) de (\d+) vehículos alquilados \((\d+)%\)\.$/i);
    if (fleetOccupancyMatch) {
        return value.replace(
            text,
            `${fleetOccupancyMatch[1]} of ${fleetOccupancyMatch[2]} vehicles rented (${fleetOccupancyMatch[3]}%).`
        );
    }

    const footerCopyrightMatch = text.match(/^© (\d{4}) SantaLucía Alquiler\. Todos los derechos reservados\.$/);
    if (footerCopyrightMatch) {
        return value.replace(text, `© ${footerCopyrightMatch[1]} SantaLucía Rental. All rights reserved.`);
    }

    const estimatedDistanceMatch = text.match(/^Distancia aproximada a la sucursal:\s*(.+)$/);
    if (estimatedDistanceMatch) {
        return value.replace(text, `Approximate distance to the branch: ${estimatedDistanceMatch[1]}`);
    }

    const rentalMatch = text.match(/^Se ha reservado el\s*/);
    if (rentalMatch) return value.replace(rentalMatch[0], 'Reserved ');

    return value;
}

export function translateAttribute(name, value, language) {
    if (language !== 'en') return value;
    if (name === 'title' || name === 'placeholder' || name === 'aria-label' || name === 'alt') {
        return translateText(value, language);
    }
    return value;
}
