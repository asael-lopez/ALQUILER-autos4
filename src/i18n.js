export function translateText(value, language) {
    if (language !== 'en' || typeof value !== 'string') return value;
    const trimmedText = value.trim();
    const text = trimmedText.replace(/\s+/g, ' ');
    const translated = englishTranslations[text] ?? additionalEnglishTranslations[text];
    if (translated !== undefined) {
        return value.replace(trimmedText, translated);
    }

    const optionsMatch = text.match(/^(\d+) opciones de categoría de vehículo disponibles$/i);
    if (optionsMatch) {
        const count = Number(optionsMatch[1]);
        const result = `${count} vehicle ${count === 1 ? 'category option' : 'category options'} available`;
        return value.replace(text, result);
    }

    const reservationsMatch = text.match(/^(\d+) reservas$/i);
    if (reservationsMatch) {
        const count = Number(reservationsMatch[1]);
        return value.replace(text, `${count} ${count === 1 ? 'reservation' : 'reservations'}`);
    }

    const maintenanceMatch = text.match(/^Mantenimiento \((\d+)\)$/i);
    if (maintenanceMatch) {
        return value.replace(text, `Maintenance (${maintenanceMatch[1]})`);
    }

    const passengerMatch = text.match(/^(\d+) pasajeros$/i);
    if (passengerMatch) {
        return value.replace(text, `${passengerMatch[1]} passengers`);
    }

    const luggageMatch = text.match(/^(\d+) maletas$/i);
    if (luggageMatch) {
        return value.replace(text, `${luggageMatch[1]} bags`);
    }

    const fleetOccupancyMatch = text.match(/^(\d+) de (\d+) vehículos alquilados \((\d+)%\)\.$/i);
    if (fleetOccupancyMatch) {
        return value.replace(
            text,
            `${fleetOccupancyMatch[1]} of ${fleetOccupancyMatch[2]} vehicles rented (${fleetOccupancyMatch[3]}%).`
        );
    }

    const footerCopyrightMatch = text.match(/^© (\d{4}) SantaLucía Alquiler\. Todos los derechos reservados\.$/);
    if (footerCopyrightMatch) {
        return value.replace(text, `© ${footerCopyrightMatch[1]} SantaLucía Rental. All rights reserved.`);
    }

    const estimatedDistanceMatch = text.match(/^Distancia aproximada a la sucursal:\s*(.+)$/);
    if (estimatedDistanceMatch) {
        return value.replace(text, `Approximate distance to the branch: ${estimatedDistanceMatch[1]}`);
    }

    const rentalMatch = text.match(/^Se ha reservado el\s*/);
    if (rentalMatch) return value.replace(rentalMatch[0], 'Reserved ');

    const countLabelMatch = text.match(/^(Todos|Oficiales|DEMO) \((\d+)\)$/);
    if (countLabelMatch) {
        const label = countLabelMatch[1] === 'Todos'
            ? 'All'
            : countLabelMatch[1] === 'Oficiales'
                ? 'Official'
                : 'DEMO';
        return value.replace(trimmedText, `${label} (${countLabelMatch[2]})`);
    }

    const countReviewMatch = text.match(/^(\d+) por revisar$/);
    if (countReviewMatch) {
        return value.replace(trimmedText, `${countReviewMatch[1]} to review`);
    }

    const vehicleMetaMatch = text.match(/^Año (\d{4}) · (.+)$/);
    if (vehicleMetaMatch) {
        return value.replace(
            trimmedText,
            `Year ${vehicleMetaMatch[1]} · ${translateText(vehicleMetaMatch[2], language)}`
        );
    }

    const translatedVehicleMetaMatch = text.match(/^Year (\d{4}) · (.+)$/);
    if (translatedVehicleMetaMatch) {
        return value.replace(
            trimmedText,
            `Year ${translatedVehicleMetaMatch[1]} · ${translateText(translatedVehicleMetaMatch[2], language)}`
        );
    }

    const pendingVehicleMetaMatch = text.match(/^Year to be confirmed · (.+)$/);
    if (pendingVehicleMetaMatch) {
        return value.replace(
            trimmedText,
            `Year to be confirmed · ${translateText(pendingVehicleMetaMatch[1], language)}`
        );
    }

    const vehicleColorSuffixMatch = text.match(/^· (.+)$/);
    if (vehicleColorSuffixMatch) {
        return value.replace(
            trimmedText,
            `· ${translateText(vehicleColorSuffixMatch[1], language)}`
        );
    }

    const estimatedLuggageMatch = text.match(/^(?:~|aprox\. )(\d+) maletas$/);
    if (estimatedLuggageMatch) {
        return value.replace(trimmedText, `~${estimatedLuggageMatch[1]} bags`);
    }

    const vehicleYearMatch = text.match(/^Año (\d{4})$/);
    if (vehicleYearMatch) {
        return value.replace(trimmedText, `Year ${vehicleYearMatch[1]}`);
    }

    const photoAltMatch = text.match(/^Foto de (.+)$/);
    if (photoAltMatch) {
        return value.replace(trimmedText, `Photo of ${photoAltMatch[1]}`);
    }

    const reservationNoticeMatch = text.match(/^Reserva #(.+) ·$/);
    if (reservationNoticeMatch) {
        return value.replace(trimmedText, `Reservation #${reservationNoticeMatch[1]} ·`);
    }

    const underReviewMatch = text.match(/^(\d+) en revisión$/);
    if (underReviewMatch) {
        return value.replace(trimmedText, `${underReviewMatch[1]} under review`);
    }

    const approveListingMatch = text.match(/^Aprobar publicación de (.+)$/);
    if (approveListingMatch) {
        return value.replace(trimmedText, `Approve listing for ${approveListingMatch[1]}`);
    }

    const editEntityMatch = text.match(/^Editar (.+)$/);
    if (editEntityMatch) {
        return value.replace(trimmedText, `Edit ${editEntityMatch[1]}`);
    }

    const deleteEntityMatch = text.match(/^Eliminar (.+)$/);
    if (deleteEntityMatch) {
        return value.replace(trimmedText, `Delete ${deleteEntityMatch[1]}`);
    }

    const pendingReservationsMatch = text.match(/^Tienes (\d+) reserva\(s\) pendientes de aprobación\.$/);
    if (pendingReservationsMatch) {
        return value.replace(
            trimmedText,
            `You have ${pendingReservationsMatch[1]} reservation(s) awaiting approval.`
        );
    }

    const weatherStatusMatch = text.match(/^El servicio de clima respondió con estado (\d+)\.$/);
    if (weatherStatusMatch) {
        return value.replace(trimmedText, `The weather service responded with status ${weatherStatusMatch[1]}.`);
    }

    const exchangeStatusMatch = text.match(/^El servicio de tipo de cambio respondió con estado (\d+)\.$/);
    if (exchangeStatusMatch) {
        return value.replace(trimmedText, `The exchange-rate service responded with status ${exchangeStatusMatch[1]}.`);
    }

    const nominatimStatusMatch = text.match(/^Nominatim respondió con estado (\d+)\.$/);
    if (nominatimStatusMatch) {
        return value.replace(trimmedText, `Nominatim responded with status ${nominatimStatusMatch[1]}.`);
    }

    const weatherSummaryMatch = text.match(/^(.*?)([^,]+), (\d+)-(\d+) °C, lluvia hasta (\d+)%$/);
    if (weatherSummaryMatch) {
        return value.replace(
            trimmedText,
            `${weatherSummaryMatch[1]}${translateText(weatherSummaryMatch[2], language)}, ${weatherSummaryMatch[3]}–${weatherSummaryMatch[4]} °C, up to ${weatherSummaryMatch[5]}% chance of rain`
        );
    }

    const estimateDistanceMatch = text.match(/^(?:📍\s*)?La dirección que buscaste en el mapa está a ([\d.,]+) km de la sucursal\.$/);
    if (estimateDistanceMatch) {
        return value.replace(
            trimmedText,
            `The address you searched for is ${estimateDistanceMatch[1]} km from the branch.`
        );
    }

    const homeVehicleLabelMatch = text.match(/^(.+)\. (.+)\. Ver nuestra flota$/);
    if (homeVehicleLabelMatch) {
        return value.replace(
            trimmedText,
            `${translateText(homeVehicleLabelMatch[1], language)}. ${translateText(homeVehicleLabelMatch[2], language)}. View our fleet`
        );
    }

    const featuredVehicleAltMatch = text.match(/^Vehículo destacado de categoría (.+)$/);
    if (featuredVehicleAltMatch) {
        return value.replace(
            trimmedText,
            `Featured ${translateText(featuredVehicleAltMatch[1], language)} vehicle`
        );
    }

    const activityDateRangeMatch = text.match(/^Mostrando: (.+) · período (.+) → (.+)\.$/);
    if (activityDateRangeMatch) {
        return value.replace(
            trimmedText,
            `Showing: ${translateText(activityDateRangeMatch[1], language)} · period ${translateText(activityDateRangeMatch[2], language)} → ${translateText(activityDateRangeMatch[3], language)}.`
        );
    }

    const movementStatusMatch = text.match(/^Disponibilidad: (.+) → (.+)$/);
    if (movementStatusMatch) {
        return value.replace(
            trimmedText,
            `Availability: ${translateText(movementStatusMatch[1], language)} → ${translateText(movementStatusMatch[2], language)}`
        );
    }

    const favoriteLabelMatch = text.match(/^(Quitar (.+) de|Agregar (.+) a) favoritos$/);
    if (favoriteLabelMatch) {
        const action = favoriteLabelMatch[1].startsWith('Quitar') ? 'Remove' : 'Add';
        const name = translateText(favoriteLabelMatch[2] || favoriteLabelMatch[3], language);
        return value.replace(trimmedText, `${action} ${name} from favorites`);
    }

    const currencyEquivalentMatch = text.match(/^≈ (.+) \(referencial, se cobra en USD\)$/);
    if (currencyEquivalentMatch) {
        return value.replace(trimmedText, `≈ ${currencyEquivalentMatch[1]} (reference only; charged in USD)`);
    }

    const currencyReferenceMatch = text.match(/^≈ (.+) \(referencial\)$/);
    if (currencyReferenceMatch) {
        return value.replace(trimmedText, `≈ ${currencyReferenceMatch[1]} (reference only)`);
    }

    const estimatedTotalMatch = text.match(/^Total estimado: (.+)$/);
    if (estimatedTotalMatch) {
        return value.replace(trimmedText, `Estimated total: ${estimatedTotalMatch[1]}`);
    }

    const estimatedEquivalentMatch = text.match(/^Equivalencia estimada: (.+) \/ hora$/);
    if (estimatedEquivalentMatch) {
        return value.replace(trimmedText, `Estimated equivalent: ${estimatedEquivalentMatch[1]} / hour`);
    }

    const reservationDateSummaryMatch = text.match(/^(.+) · (.+) al (.+)$/);
    if (reservationDateSummaryMatch) {
        return value.replace(
            trimmedText,
            `${reservationDateSummaryMatch[1]} · ${reservationDateSummaryMatch[2]} to ${reservationDateSummaryMatch[3]}`
        );
    }

    const currencyNoteMatch = text.match(/^Equivalencia referencial · tasas del (.+?)( \(sin conexión, última guardada\))?\. Se cobra en USD\.$/);
    if (currencyNoteMatch) {
        return value.replace(
            trimmedText,
            `Reference equivalent · rates as of ${currencyNoteMatch[1]}${currencyNoteMatch[2] ? ' (offline, last saved)' : ''}. Charged in USD.`
        );
    }

    const branchWeatherMatch = text.match(/^Clima en la sucursal: (.+)$/);
    if (branchWeatherMatch) {
        return value.replace(
            trimmedText,
            `Weather at the branch: ${translateText(branchWeatherMatch[1], language)}`
        );
    }

    const dailyRateMatch = text.match(/^Tarifa aplicada: (.+)\/día(?: · (\d+)% menos por duración)?(?: · Extras: (.+)\/día)?$/);
    if (dailyRateMatch) {
        const discount = dailyRateMatch[2] ? ` · ${dailyRateMatch[2]}% longer rental discount` : '';
        const extras = dailyRateMatch[3] ? ` · Add-ons: ${dailyRateMatch[3]}/day` : '';
        return value.replace(trimmedText, `Applied rate: ${dailyRateMatch[1]}/day${discount}${extras}`);
    }

    const hourlyRateMatch = text.match(/^≈ (.+)\/h estimado$/);
    if (hourlyRateMatch) {
        return value.replace(trimmedText, `≈ ${hourlyRateMatch[1]}/h estimated`);
    }

    const dailyRateSuffixMatch = text.match(/^(.+) \/ día$/);
    if (dailyRateSuffixMatch) {
        return value.replace(trimmedText, `${dailyRateSuffixMatch[1]} / day`);
    }

    const reservationDiscountMatch = text.match(/^(\d+)% de descuento por duración$/);
    if (reservationDiscountMatch) {
        return value.replace(trimmedText, `${reservationDiscountMatch[1]}% duration discount`);
    }

    for (const [pattern, format] of dynamicToastTranslations) {
        const match = text.match(pattern);
        if (match) return value.replace(trimmedText, format(match, language));
    }

    const registeredVehicleMatch = text.match(/^(.+) \((.+)\) se registró en la flota$/);
    if (registeredVehicleMatch) {
        return value.replace(
            trimmedText,
            `${registeredVehicleMatch[1]} (${translateText(registeredVehicleMatch[2], language)}) was added to the fleet`
        );
    }

    const publishedVehicleMatch = text.match(/^(.+) aprobado y visible en el catálogo público$/);
    if (publishedVehicleMatch) {
        return value.replace(trimmedText, `${publishedVehicleMatch[1]} approved and visible in the public catalog`);
    }

    const rejectedVehicleMatch = text.match(/^(.+) rechazado; no aparecerá en el catálogo$/);
    if (rejectedVehicleMatch) {
        return value.replace(trimmedText, `${rejectedVehicleMatch[1]} rejected; it will not appear in the catalog`);
    }

    return value;
}

export function translateAttribute(name, value, language) {
    if (language !== 'en') return value;
    if (name === 'title' || name === 'placeholder' || name === 'aria-label' || name === 'alt' || name === 'data-tooltip') {
        return translateText(value, language);
    }
    return value;
}
